import fs from 'node:fs';
const CDP = 'http://127.0.0.1:9333';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const targets = await (await fetch(CDP + '/json')).json();
const page = targets.find((t) => t.type === 'page' && t.url.includes('bubble-vanguard.pages.dev'));
const ws = new WebSocket(page.webSocketDebuggerUrl);
let seq = 0;
const pending = new Map();
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.reject(new Error(JSON.stringify(m.error))) : p.resolve(m.result); } });
await new Promise((r) => ws.addEventListener('open', r, { once: true }));
const send = (method, params = {}) => new Promise((resolve, reject) => { const id = ++seq; pending.set(id, { resolve, reject }); ws.send(JSON.stringify({ id, method, params })); });
const ev = async (expression) => (await send('Runtime.evaluate', { expression, awaitPromise: true, returnByValue: true })).result?.value;
await send('Runtime.enable'); await send('Page.enable');
console.log('buttons:', await ev(`JSON.stringify(Array.from(document.querySelectorAll('button')).map(b => ({id:b.id, cls:b.className, text:b.innerText.trim().slice(0,20)})).slice(0,20))`));
console.log('overlay:', await ev(`document.querySelector('#novelScreen') ? {hidden: document.querySelector('#novelScreen').hidden, cls: document.querySelector('#novelScreen').className} : null`));
console.log('click:', await ev(`(() => { const b = Array.from(document.querySelectorAll('button')).find(x => x.textContent.includes('小说')); if (!b) return 'not-found'; b.click(); return b.id + '|' + b.className; })()`));
await sleep(3000);
console.log('after:', await ev(`JSON.stringify({overlay: document.querySelector('#novelScreen')?.className, cards: document.querySelectorAll('.chapter-card').length, status: document.querySelector('#libraryStatus')?.innerText, body: document.body.innerText.slice(0,400)})`));
const shot = await send('Page.captureScreenshot', { format: 'png', captureBeyondViewport: false });
fs.writeFileSync('shots-browser/pages-live-library-2.png', Buffer.from(shot.data, 'base64'));
ws.close();
