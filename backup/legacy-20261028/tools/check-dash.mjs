import { writeFile } from 'node:fs/promises';
const CDP = 'http://127.0.0.1:9336';
const targets = await (await fetch(CDP + '/json')).json();
const page = targets.find(t => t.type === 'page');
if (!page) throw new Error('no page');
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.reject(new Error(m.error.message)) : p.resolve(m.result); } });
await new Promise((r, j) => { ws.addEventListener('open', r, { once: true }); ws.addEventListener('error', j, { once: true }); });
const send = (method, params = {}) => new Promise((resolve, reject) => { const n = ++id; pending.set(n, { resolve, reject }); ws.send(JSON.stringify({ id: n, method, params })); });
const wait = ms => new Promise(r => setTimeout(r, ms));
await send('Page.enable'); await send('Runtime.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
await send('Page.navigate', { url: 'https://dash.cloudflare.com/' });
await wait(7000);
const r = await send('Runtime.evaluate', { expression: `JSON.stringify({href:location.href,title:document.title,text:document.body.innerText.slice(0,600),cookies:document.cookie.slice(0,300)})`, returnByValue: true });
console.log(r.result.value);
const shot = await send('Page.captureScreenshot', { format: 'png', fromSurface: true });
await writeFile('shots-browser/cf-dash-session.png', Buffer.from(shot.data, 'base64'));
ws.close();
